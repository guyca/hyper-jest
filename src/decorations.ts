/**
 * Gutter + inline decorations (plan: "Result -> UI mapping", Gutter and Inline text rows).
 *
 * One TextEditorDecorationType per gutter variant (state x hollow x snapshot, plus declaration
 * icons) and one per inline kind (error / value / log). Per-line content varies only through
 * `renderOptions.after.contentText` so the number of types stays fixed. Every bucket is applied on
 * every refresh, with `[]` for empty ones, so stale decorations never linger.
 */
import * as vscode from 'vscode';
import type { TestStatus } from './core/protocol';
import type { LineState, LineViewFile } from './core/resultModel';
import type { HyperJestSettings } from './core/settingsModel';
import type { ParsedFile } from './core/testModel';
import { type DeclarationState, IconAssets, type IconState, LINE_STATES, DECLARATION_STATES } from './iconAssets';
import { inlineTextFor } from './results/lineView';

/** Two EM spaces, as Wallaby draws them (research: live values report section 1). */
export const INLINE_PREFIX = '  ';

export type InlineKind = 'error' | 'log' | 'value';

export interface DecorationPlan {
  /** variant key (`state|hollow|snapshot`) -> 0-based lines */
  gutter: Map<string, number[]>;
  /** declaration key (`state` or `state|hollow`) -> 0-based lines */
  declarations: Map<string, number[]>;
  inline: Array<{ line: number; kind: InlineKind; text: string }>;
}

export function variantKey(state: IconState, hollow: boolean, snapshot: boolean): string {
  return `${state}|${hollow ? 1 : 0}|${snapshot ? 1 : 0}`;
}

export function declarationKey(state: DeclarationState, hollow: boolean): string {
  return hollow ? `${state}|hollow` : state;
}

export function declarationStateFor(status: TestStatus | 'unknown'): DeclarationState {
  switch (status) {
    case 'passed': case 'focused': return 'declPassed';
    case 'failed': case 'errored': return 'declFailed';
    case 'unknown': return 'declUnknown';
    default: return 'declSkipped';
  }
}

/**
 * Pure: turns a line view into decoration buckets. Declaration icons win over coverage icons on
 * the same line (two gutter icons would overlap).
 */
export function planDecorations(view: LineViewFile, settings: Pick<HyperJestSettings, 'gutter' | 'inline'>, showDeclarations: boolean): DecorationPlan {
  const plan: DecorationPlan = { gutter: new Map(), declarations: new Map(), inline: [] };
  const declLines = new Set<number>();
  if (settings.gutter.enabled && showDeclarations) {
    for (const [line, decl] of view.declarations) {
      const state = declarationStateFor(decl.status);
      const lv = view.lines.get(line);
      // Stale declaration results are hollow like everything else.
      const key = declarationKey(state, !!lv?.stale);
      const list = plan.declarations.get(key) ?? [];
      list.push(line);
      plan.declarations.set(key, list);
      declLines.add(line);
    }
  }
  for (const lv of view.lines.values()) {
    if (settings.gutter.enabled && lv.state && !declLines.has(lv.line)) {
      const key = variantKey(lv.state, lv.stale, lv.snapshot);
      const list = plan.gutter.get(key) ?? [];
      list.push(lv.line);
      plan.gutter.set(key, list);
    }
    const text = inlineTextFor(lv, settings.inline);
    if (text) plan.inline.push({ line: lv.line, kind: text.kind, text: text.text });
  }
  return plan;
}

/** Whether HyperJest should draw its own test-declaration icons given the user's testing settings. */
export function shouldShowDeclarationIcons(mode: HyperJestSettings['gutter']['testDeclarations'], testingGutterEnabled: boolean): boolean {
  if (mode === 'never') return false;
  if (mode === 'always') return true;
  return !testingGutterEnabled;
}

export class DecorationManager implements vscode.Disposable {
  private gutterTypes = new Map<string, vscode.TextEditorDecorationType>();
  private declTypes = new Map<string, vscode.TextEditorDecorationType>();
  private inlineTypes: Record<InlineKind, vscode.TextEditorDecorationType>;
  private disposed = false;
  /** IconAssets colour key the gutter/declaration types point at. */
  private typesColorKey = '';

  constructor(private readonly icons: IconAssets, private readonly settings: () => HyperJestSettings) {
    this.inlineTypes = this.createInlineTypes();
    this.createGutterTypes();
  }

  /**
   * Call after `hyperjest.colors.*` changed; recreates icon types (icons are regenerated by IconAssets).
   * Compares against the colours the current types were built with, so it also works when the caller
   * already pushed the new colours into the shared IconAssets.
   */
  async onColorsChanged(): Promise<void> {
    this.icons.setColors(this.settings().colors);
    if (this.icons.colorKey === this.typesColorKey) return;
    await this.icons.ensure();
    if (this.disposed) return;
    for (const t of this.gutterTypes.values()) t.dispose();
    for (const t of this.declTypes.values()) t.dispose();
    this.createGutterTypes();
  }

  /** Applies the view to one editor (all buckets, empty ones included). */
  apply(editor: vscode.TextEditor, view: LineViewFile | undefined, _parsed?: ParsedFile): void {
    if (this.disposed) return;
    const settings = this.settings();
    const testingGutter = vscode.workspace.getConfiguration('testing').get<boolean>('gutterEnabled', true);
    const plan = view ? planDecorations(view, settings, shouldShowDeclarationIcons(settings.gutter.testDeclarations, testingGutter))
      : { gutter: new Map(), declarations: new Map(), inline: [] } as DecorationPlan;
    const doc = editor.document;
    const lineCount = doc.lineCount;
    const rangesFor = (lines: number[] | undefined): vscode.Range[] =>
      (lines ?? []).filter(l => l < lineCount).map(l => doc.lineAt(l).range);

    for (const [key, type] of this.gutterTypes) editor.setDecorations(type, rangesFor(plan.gutter.get(key)));
    for (const [key, type] of this.declTypes) editor.setDecorations(type, rangesFor(plan.declarations.get(key)));

    const buckets: Record<InlineKind, vscode.DecorationOptions[]> = { error: [], log: [], value: [] };
    for (const item of plan.inline) {
      if (item.line >= lineCount) continue;
      const line = doc.lineAt(item.line);
      const range = new vscode.Range(item.line, line.firstNonWhitespaceCharacterIndex, item.line, line.range.end.character);
      buckets[item.kind].push({ range, renderOptions: { after: { contentText: INLINE_PREFIX + item.text } } });
    }
    for (const kind of ['error', 'log', 'value'] as InlineKind[]) editor.setDecorations(this.inlineTypes[kind], buckets[kind]);
  }

  /** Clears every HyperJest decoration from an editor. */
  clear(editor: vscode.TextEditor): void {
    this.apply(editor, undefined);
  }

  /** Re-applies views to the given editors (`onDidChangeVisibleTextEditors`, store changes). */
  refreshAll(editors: readonly vscode.TextEditor[], viewFor: (path: string) => LineViewFile | undefined): void {
    for (const editor of editors) {
      if (editor.document.uri.scheme !== 'file') continue;
      this.apply(editor, viewFor(editor.document.uri.fsPath));
    }
  }

  dispose(): void {
    this.disposed = true;
    for (const t of this.gutterTypes.values()) t.dispose();
    for (const t of this.declTypes.values()) t.dispose();
    for (const t of Object.values(this.inlineTypes)) t.dispose();
    this.gutterTypes.clear();
    this.declTypes.clear();
  }

  private createGutterTypes(): void {
    this.typesColorKey = this.icons.colorKey;
    this.gutterTypes = new Map();
    this.declTypes = new Map();
    for (const state of LINE_STATES) {
      for (const hollow of [false, true]) {
        for (const snapshot of [false, true]) {
          this.gutterTypes.set(variantKey(state, hollow, snapshot), this.gutterType(state, hollow, snapshot));
        }
      }
    }
    for (const state of DECLARATION_STATES) {
      this.declTypes.set(declarationKey(state, false), this.gutterType(state, false, false));
      this.declTypes.set(declarationKey(state, true), this.gutterType(state, true, false));
    }
  }

  private gutterType(state: IconState, hollow: boolean, snapshot: boolean): vscode.TextEditorDecorationType {
    return vscode.window.createTextEditorDecorationType({
      isWholeLine: true,
      rangeBehavior: vscode.DecorationRangeBehavior.ClosedClosed,
      gutterIconSize: 'contain',
      gutterIconPath: this.icons.pathFor(state, hollow, snapshot),
      overviewRulerColor: state === 'errorSource' ? this.icons.currentColors.errorSource : undefined,
      overviewRulerLane: state === 'errorSource' ? vscode.OverviewRulerLane.Right : undefined,
    });
  }

  private createInlineTypes(): Record<InlineKind, vscode.TextEditorDecorationType> {
    const base = { isWholeLine: true, rangeBehavior: vscode.DecorationRangeBehavior.ClosedClosed };
    return {
      error: vscode.window.createTextEditorDecorationType({ ...base, after: { color: new vscode.ThemeColor('hyperjest.inlineError.foreground') } }),
      log: vscode.window.createTextEditorDecorationType({ ...base, after: { color: new vscode.ThemeColor('hyperjest.inlineLog.foreground') } }),
      value: vscode.window.createTextEditorDecorationType({
        ...base,
        after: {
          color: new vscode.ThemeColor('hyperjest.inlineValue.foreground'),
          border: '1px solid',
          borderColor: new vscode.ThemeColor('hyperjest.inlineValue.foreground'),
          margin: '0 0 0 0',
        },
      }),
    };
  }
}

/** Exposed for tests: the states the manager creates types for. */
export const GUTTER_LINE_STATES: readonly LineState[] = LINE_STATES;
